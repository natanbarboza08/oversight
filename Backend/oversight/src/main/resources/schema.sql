-- CTI Insights — esquema do banco PostgreSQL (Azure Database for PostgreSQL – Servidor Flexível)
-- Executado automaticamente pelo Spring Boot ao ligar (spring.sql.init). O Spring só grava USUÁRIO; os dados do upload são gravados SÓ pelo Python.
-- É seguro rodar várias vezes: "IF NOT EXISTS" só cria o que ainda não existe.

-- ===== USUÁRIOS (cadastro, login e liberação de acesso) =====
CREATE TABLE IF NOT EXISTS usuario (                                            -- tabela dos usuários
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,            -- número gerado pelo banco (1, 2, 3...)
  nome          VARCHAR(120) NOT NULL,                                          -- nome (obrigatório)
  email         VARCHAR(160) NOT NULL UNIQUE,                                   -- e-mail único: ninguém repete
  senha_hash    VARCHAR(100) NOT NULL,                                          -- senha criptografada com BCrypt (nunca a senha pura)
  matricula     VARCHAR(30),                                                    -- matrícula do usuário (opcional)
  turma         VARCHAR(60),                                                    -- turma (opcional)
  perfil        VARCHAR(20)  NOT NULL DEFAULT 'USER',                           -- USER (usuário comum) ou ADMIN (administrador)
  status        VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',                       -- PENDENTE, APROVADO ou BLOQUEADO
  criado_em     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP                 -- quando a conta foi criada
);

-- ===== LOTES (cada envio de planilha é um lote; criado e gravado só pelo PYTHON) =====
CREATE TABLE IF NOT EXISTS upload_lote (                                        -- tabela dos lotes
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,         -- id do lote
  arquivo_nome     VARCHAR(255) NOT NULL,                                       -- nome do arquivo enviado
  enviado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,                -- data e hora do envio
  status           VARCHAR(20) NOT NULL,                                        -- PROCESSANDO, PROCESSADO ou ERRO (quem grava é o Python)
  total_linhas     INT NOT NULL DEFAULT 0,                                      -- total de linhas da planilha
  linhas_validas   INT NOT NULL DEFAULT 0,                                      -- quantas estavam válidas
  linhas_invalidas INT NOT NULL DEFAULT 0,                                      -- quantas tinham erro
  linhas_com_aviso INT NOT NULL DEFAULT 0,                                      -- quantas tinham só aviso
  mensagem         VARCHAR(500)                                                 -- mensagem mostrada na tela
);

-- ===== DADOS VÁLIDOS (gravados pelo Python depois da limpeza) =====
CREATE TABLE IF NOT EXISTS consultor (                                          -- consultores, sem repetir
  id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,                    -- id do consultor
  nome  VARCHAR(120) NOT NULL UNIQUE                                            -- nome único
);
CREATE TABLE IF NOT EXISTS segmento (                                          -- segmentos de mercado, sem repetir
  id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,                    -- id do segmento
  nome  VARCHAR(40) NOT NULL UNIQUE                                             -- nome único (Indústria, Comércio...)
);
CREATE TABLE IF NOT EXISTS servico (                                            -- serviços oferecidos, sem repetir
  id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,                    -- id do serviço
  nome  VARCHAR(120) NOT NULL UNIQUE                                            -- nome único (Internet Dedicada, Firewall...)
);
CREATE TABLE IF NOT EXISTS cliente (                                            -- clientes válidos
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,       -- id do cliente
  lote_id            BIGINT NOT NULL REFERENCES upload_lote(id) ON DELETE CASCADE,  -- lote de origem
  codigo_cti         VARCHAR(60) NOT NULL,                                      -- código do cliente
  nome               VARCHAR(255) NOT NULL,                                     -- nome do cliente
  consultor_id       BIGINT NOT NULL REFERENCES consultor(id),                  -- consultor responsável
  segmento_id        BIGINT NOT NULL REFERENCES segmento(id),                   -- segmento padronizado
  nivel              CHAR(1) NOT NULL,                                          -- nível A, B ou C
  faturamento_anual  NUMERIC(16,2) NOT NULL,                                    -- FATURAMENTO ANUAL com 2 casas (base da média e da mediana)
  cidade             VARCHAR(120),                                              -- cidade
  uf                 CHAR(2),                                                   -- UF
  UNIQUE (lote_id, codigo_cti)                                                  -- não repete o código dentro do lote
);
CREATE TABLE IF NOT EXISTS contrato (                                           -- contratos: qual cliente contratou qual serviço
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,        -- id do contrato
  cliente_id        BIGINT NOT NULL REFERENCES cliente(id) ON DELETE CASCADE,   -- cliente (apagou o cliente, apaga o contrato)
  servico_id        BIGINT NOT NULL REFERENCES servico(id),                     -- serviço contratado
  data_contratacao  DATE NOT NULL,                                              -- data da contratação
  UNIQUE (cliente_id, servico_id)                                               -- o cliente não contrata o mesmo serviço duas vezes
);

-- ===== RESULTADO DAS CONTAS (o dashboard lê daqui) =====
CREATE TABLE IF NOT EXISTS estatistica_lote (                                   -- um resultado por lote
  lote_id    BIGINT PRIMARY KEY REFERENCES upload_lote(id) ON DELETE CASCADE,   -- lote ao qual o resultado pertence
  gerado_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,                      -- quando o Python gerou
  resultado  TEXT NOT NULL                                                      -- JSON com média, mediana e dados dos gráficos
);
